import puppeteer from "puppeteer-core";
const sleep = ms => new Promise(r => setTimeout(r, ms));
const H = "http://localhost:8080";
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const errs = [];
const jar = {};
const call = async (who, path, body, method = "POST") => {
  const r = await fetch(H + path, { method, headers: { "content-type": "application/json", origin: H, cookie: jar[who] ?? "" }, body: method === "GET" ? undefined : JSON.stringify(body ?? {}) });
  const set = r.headers.get("set-cookie"); if (set) jar[who] = set.split(";")[0];
  return r.json().catch(() => ({}));
};
await call("a", "/api/session", { name: "Ann" }); await call("b", "/api/session", { name: "Ben" });
const { game } = await call("a", "/api/maze/matches", {});
await call("b", `/api/maze/matches/${game.id}/join`, {});
const { token } = await call("a", `/api/maze/matches/${game.id}/spectate`, null, "GET");
const S = await b.newPage(); await S.setViewport({ width: 1440, height: 900 });
S.on("pageerror", e => errs.push(e.message));
await S.goto(`${H}/watch/${token}`, { waitUntil: "domcontentloaded" }); await sleep(2500);
await call("a", `/api/maze/matches/${game.id}/ready`, {}); await call("b", `/api/maze/matches/${game.id}/ready`, {});
await sleep(4000);
await call("b", `/api/maze/matches/${game.id}/forfeit`, {}); await sleep(800);
console.log("after forfeit:", await S.evaluate(() => document.getElementById("spec-title").textContent));
const next = await call("a", `/api/maze/matches/${game.id}/rematch`, {});
await sleep(600);
console.log("on rematch:", await S.evaluate(() => document.getElementById("spec-title").textContent));
await S.screenshot({ path: "/tmp/driver/spec-following.png" });
await sleep(3500);
console.log("then:", await S.evaluate(() => document.getElementById("spec-title").textContent), "url still token:", S.url().endsWith(token));
await call("a", `/api/maze/matches/${next.game.id}/ready`, {}); await call("b", `/api/maze/matches/${next.game.id}/ready`, {});
await sleep(1500);
console.log("rematch countdown:", await S.evaluate(() => [document.getElementById("spec-title").textContent, document.body.dataset.phase]));
console.log("errors", errs);
await b.close();
